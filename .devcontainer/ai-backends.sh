}

action="$(resolve_action "${1:-}")"
if [ "$(basename "$0")" = "ai-backends.sh" ] && [ "$#" -gt 0 ]; then
  shift
fi

case "${action}" in
  install) install_backend_support ;;
  claude-zai) launch_claude_backend zai "$@" ;;
  claude-openrouter) launch_claude_backend openrouter "$@" ;;
  codex-zai) launch_codex_backend zai "$@" ;;
  codex-openrouter) launch_codex_backend openrouter "$@" ;;
  help | -h | --help) print_help ;;
  *) die "Unknown action: ${action}" ;;
esac
